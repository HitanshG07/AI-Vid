"""AI-Vid V6 learning brief (0 tokens, pure Python): what is working on the channel -> ledger/LEARNING_BRIEF.md.

Reads ledger/pipeline.db (views_24h / views_7d / likes_7d from analytics_sync.py) and, when present,
ledger/studio_export.csv (a YouTube Studio export; columns matched loosely: video id or title, "Viewed (%)" /
"Stayed to watch", "Average percentage viewed"). Ranks rule_type, opening_variant, ending_type, set, title style and
duration bucket, best to worst. story_gen.py --auto feeds the brief to the writer model.

  python pipeline/learning_brief.py
"""
from __future__ import annotations
import csv, json, re, sqlite3, statistics
from pathlib import Path
import yaml
from config_loader import ROOT

LIVE = ("UPLOADED_PRIVATE", "SCHEDULED", "POSTED_MANUAL", "APPROVED")
HOOK = re.compile(r"^\s*in this (world|town)\b", re.I)


def _num(v) -> float | None:
    try:
        return float(str(v).replace("%", "").replace(",", "").strip())
    except (TypeError, ValueError):
        return None


def load_studio_export(path: Path) -> dict:
    """{video_id_or_lower_title: {"viewed": %, "apv": %}} from a Studio CSV export (any column order)."""
    out = {}
    if not path.exists():
        return out
    with path.open(encoding="utf-8-sig", newline="") as f:
        for row in csv.DictReader(f):
            low = {k.lower().strip(): v for k, v in row.items() if k}
            key = next((low[k] for k in low if k in ("content", "video id", "video_id", "youtube_video_id")), None) \
                or next((low[k] for k in low if "title" in k), None)
            if not key:
                continue
            viewed = next((_num(low[k]) for k in low if "average" not in k
                           and ("viewed (%)" in k or "stayed to watch" in k or k == "viewed_pct")), None)
            apv = next((_num(low[k]) for k in low if "average percentage viewed" in k or k in ("apv", "apv_pct")), None)
            out[key.strip().lower()] = {"viewed": viewed, "apv": apv}
    return out


def episode_rows(root: Path, db_path: Path) -> list[dict]:
    con = sqlite3.connect(str(db_path)); con.row_factory = sqlite3.Row
    rows = [dict(r) for r in con.execute(
        f"SELECT * FROM episodes WHERE status IN ({','.join('?' * len(LIVE))})", LIVE)]
    con.close()
    studio = load_studio_export(root / "ledger" / "studio_export.csv")
    for r in rows:
        sdir = Path(r["story_dir"]) if Path(r["story_dir"]).is_absolute() else root / r["story_dir"]
        spec, dur = {}, None
        if (sdir / "story.yaml").exists():
            spec = yaml.safe_load((sdir / "story.yaml").read_text(encoding="utf-8")) or {}
        if (sdir / "beats.json").exists():
            b = json.loads((sdir / "beats.json").read_text(encoding="utf-8"))
            dur = sum(float(x.get("dur", 0)) for x in (b.get("beats", b) if isinstance(b, dict) else b))
        r["set"] = spec.get("set", "")
        r["title"] = r.get("title") or spec.get("title", "")
        r["title_style"] = "In This World/Town hook" if HOOK.match(r["title"]) else "other title"
        r["duration"] = "unknown" if dur is None else ("<40s" if dur < 40 else "40-50s" if dur <= 50 else ">50s")
        st = studio.get(str(r.get("youtube_video_id", "")).lower()) or studio.get(r["title"].strip().lower()) or {}
        r["viewed"], r["apv"] = st.get("viewed"), st.get("apv")
    return rows


def rank(rows: list[dict], dim: str) -> list[tuple[str, int, float, float | None, float | None]]:
    groups = {}
    for r in rows:
        groups.setdefault(r.get(dim) or "(blank)", []).append(r)
    def avg(vals):
        vals = [v for v in vals if v is not None]
        return statistics.mean(vals) if vals else None
    out = [(k, len(v), avg([x.get("views_7d") or x.get("views_24h") or 0 for x in v]) or 0.0,
            avg([x["viewed"] for x in v]), avg([x["apv"] for x in v])) for k, v in groups.items()]
    # APV decides only when every group has it (a partial Studio export must not bury un-exported episodes)
    by_apv = all(t[4] is not None for t in out)
    return sorted(out, key=lambda t: (t[4], t[2]) if by_apv else (t[2], t[4] or 0), reverse=True)


def build_brief(root: Path = ROOT, db_path: Path | None = None) -> str:
    rows = episode_rows(root, db_path or (root / "ledger" / "pipeline.db"))
    lines = ["# Learning Brief (auto, 0 tokens)", "",
             "Generated by `pipeline/learning_brief.py` from `ledger/pipeline.db`"
             + (" + `ledger/studio_export.csv`" if (root / "ledger" / "studio_export.csv").exists() else "") + ".", ""]
    if not rows:
        lines += ["No published episodes with performance data yet. Until there is data, follow",
                  "`templates/style_anchors.md`: In This World/Town hook titles, one visible rule, 22 short beats,",
                  "emotional stakes, 40-50 s."]
        return "\n".join(lines) + "\n"
    lines.append(f"Based on {len(rows)} published episode(s). Ranked best first by APV % when every group "
                 "has a Studio export, otherwise by 7-day views.")
    for dim, label in (("rule_type", "Rule type"), ("opening_variant", "Opening"), ("ending_type", "Ending"),
                       ("set", "Set"), ("title_style", "Title style"), ("duration", "Duration")):
        ranked = rank(rows, dim)
        lines += ["", f"## {label}", "| value | episodes | avg views | viewed % | APV % |", "|---|---|---|---|---|"]
        for k, n, v, vw, apv in ranked:
            fmt = lambda x: "-" if x is None else f"{x:.0f}"
            lines.append(f"| {k} | {n} | {v:.0f} | {fmt(vw)} | {fmt(apv)} |")
        if len(ranked) > 1:
            lines.append(f"Top: **{ranked[0][0]}**. Bottom: **{ranked[-1][0]}**.")
    return "\n".join(lines) + "\n"


def main():
    out = ROOT / "ledger" / "LEARNING_BRIEF.md"
    out.write_text(build_brief(), encoding="utf-8")
    print("LEARNING BRIEF:", out)


if __name__ == "__main__":
    main()
